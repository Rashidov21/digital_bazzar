let currentLang = localStorage.getItem("lang") || "kg";

function applyLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang === "kg" ? "ky" : "ru";

  document.querySelectorAll("[data-lang]").forEach((el) => {
    const key = el.dataset.lang;
    if (translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-lang-placeholder]").forEach((el) => {
    const key = el.dataset.langPlaceholder;
    if (translations[lang][key] !== undefined) {
      el.setAttribute("placeholder", translations[lang][key]);
    }
  });

  updateLangSwitcherUI(lang);
}

function updateLangSwitcherUI(lang) {
  document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.langSwitch === lang);
  });
}

function initLanguageSwitcher() {
  document.querySelectorAll("[data-lang-switch]").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.langSwitch));
  });
  applyLanguage(currentLang);
}

document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
